def build_benchmark_cases(output_path: Path = Path("evaluation/benchmark_cases.json")) -> dict:
    retail_db, _ = ensure_benchmark_fixtures()
    cases = []
    for raw in RAW_CASES:
        case = dict(raw)
        case["float_tolerance"] = 0.01
        if case["expected_outcome"] == "success" and case["reference_sql"]:
            rows = compute_golden_result(retail_db, case["reference_sql"])
            case["expected_rows"] = rows
            case["expected_columns"] = list(rows[0].keys()) if rows else []
        else:
            case["expected_rows"] = []
            case["expected_columns"] = []
        cases.append(case)

    data = {
        "benchmark_name": "QueryPilot Golden Evaluation Suite",
        "version": "2.0.0",
        "fixture_database": "evaluation/fixtures/benchmark.sqlite3",
        "total_cases": len(cases),
        "cases": cases,
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(data, indent=2) + "\n")
    return data


if __name__ == "__main__":
    data = build_benchmark_cases()
    print(f"Generated {data['total_cases']} benchmark cases in evaluation/benchmark_cases.json")
